-- ============================================================
-- BANCO DE DADOS: PROJETOS
-- ============================================================

CREATE DATABASE IF NOT EXISTS Projetos
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE Projetos;


-- ============================================================
-- TABELA: USUARIOS
-- ============================================================

CREATE TABLE IF NOT EXISTS USUARIOS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(255) NOT NULL UNIQUE,
    SENHA VARCHAR(255) NOT NULL,
    TIPO VARCHAR(20) NOT NULL DEFAULT 'usuario',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP
);

-- ============================================================
-- TABELA: IDEIAS
-- ============================================================

CREATE TABLE IF NOT EXISTS IDEIAS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    USUARIOS_ID INT NOT NULL,
    TITULO VARCHAR(100) NOT NULL,
    DESCRICAO TEXT NOT NULL,
    CATEGORIA VARCHAR(50) NOT NULL DEFAULT 'Geral',
    STATUS VARCHAR(30) NOT NULL DEFAULT 'Disponível',
    ANONIMO BOOLEAN NOT NULL DEFAULT FALSE,
    VISIBILIDADE VARCHAR(20) NOT NULL DEFAULT 'Publica',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT fk_ideias_usuario
        FOREIGN KEY (USUARIOS_ID)
        REFERENCES USUARIOS(ID)
        ON DELETE CASCADE
);


-- ============================================================
-- TABELA: COMENTARIOS
-- ============================================================

CREATE TABLE IF NOT EXISTS COMENTARIOS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    IDEIAS_ID INT NOT NULL,
    USUARIOS_ID INT NOT NULL,
    PARENT_ID INT NULL DEFAULT NULL,
    COMENTARIOS TEXT NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_comentarios_ideia
        FOREIGN KEY (IDEIAS_ID)
        REFERENCES IDEIAS(ID)
        ON DELETE CASCADE,

    CONSTRAINT fk_comentarios_usuario
        FOREIGN KEY (USUARIOS_ID)
        REFERENCES USUARIOS(ID)
        ON DELETE CASCADE,

    CONSTRAINT fk_comentarios_parent
        FOREIGN KEY (PARENT_ID)
        REFERENCES COMENTARIOS(ID)
        ON DELETE CASCADE
);


-- ============================================================
-- TABELA: FAVORITOS
-- ============================================================

CREATE TABLE IF NOT EXISTS FAVORITOS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    USUARIOS_ID INT NOT NULL,
    IDEIAS_ID INT NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_favoritos_usuario
        FOREIGN KEY (USUARIOS_ID)
        REFERENCES USUARIOS(ID)
        ON DELETE CASCADE,

    CONSTRAINT fk_favoritos_ideia
        FOREIGN KEY (IDEIAS_ID)
        REFERENCES IDEIAS(ID)
        ON DELETE CASCADE,

    CONSTRAINT unique_usuario_ideia_favorito
        UNIQUE (USUARIOS_ID, IDEIAS_ID)
);


-- ============================================================
-- TABELA: VISUALIZACOES
-- ============================================================

CREATE TABLE IF NOT EXISTS VISUALIZACOES (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    IDEIAS_ID INT NOT NULL,
    USUARIOS_ID INT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_visualizacoes_ideia
        FOREIGN KEY (IDEIAS_ID)
        REFERENCES IDEIAS(ID)
        ON DELETE CASCADE,

    CONSTRAINT unique_visualizacao_usuario_ideia
        UNIQUE (IDEIAS_ID, USUARIOS_ID)
);

-- ============================================================
-- TABELA: RASCUNHO
-- ============================================================

CREATE TABLE IF NOT EXISTS RASCUNHO (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    USUARIOS_ID INT NOT NULL,
    TITULO VARCHAR(100) NOT NULL,
    DESCRICAO TEXT NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT fk_rascunho_usuario
        FOREIGN KEY (USUARIOS_ID)
        REFERENCES USUARIOS(ID)
        ON DELETE CASCADE
);


-- ============================================================
-- TABELA: REFRESH_TOKENS
-- ============================================================

sql
CREATE TABLE IF NOT EXISTS REFRESH_TOKENS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    USUARIOS_ID INT NOT NULL,
    TOKEN_HASH CHAR(64) NOT NULL UNIQUE,
    EXPIRES_AT DATETIME NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    REVOKED_AT DATETIME NULL,
    CONSTRAINT fk_refresh_usuario
        FOREIGN KEY (USUARIOS_ID)
        REFERENCES USUARIOS(ID)
        ON DELETE CASCADE
);


-- ============================================================
-- TABELA: ANEXOS
-- ============================================================
CREATE TABLE IF NOT EXISTS ANEXOS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    IDEIAS_ID INT NOT NULL,
    NOME_ARQUIVO VARCHAR(255) NOT NULL,
    NOME_SALVO VARCHAR(255) NOT NULL,
    CAMINHO VARCHAR(500) NOT NULL,
    TIPO VARCHAR(100) NOT NULL,
    TAMANHO INT NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_anexos_ideia
        FOREIGN KEY (IDEIAS_ID)
        REFERENCES IDEIAS(ID)
        ON DELETE CASCADE
);


-- ============================================================
-- TABELA: CURTIDAS
-- ============================================================

CREATE TABLE IF NOT EXISTS CURTIDAS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    IDEIAS_ID INT NOT NULL,
    USUARIOS_ID INT NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_curtidas_ideia
        FOREIGN KEY (IDEIAS_ID)
        REFERENCES IDEIAS(ID)
        ON DELETE CASCADE,

    CONSTRAINT fk_curtidas_usuario
        FOREIGN KEY (USUARIOS_ID)
        REFERENCES USUARIOS(ID)
        ON DELETE CASCADE,

    CONSTRAINT uq_curtida_usuario_ideia
        UNIQUE (IDEIAS_ID, USUARIOS_ID)
);
-- ============================================================
-- TABELA: DENUNCIAS
-- ============================================================

CREATE TABLE IF NOT EXISTS DENUNCIAS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    IDEIAS_ID INT NULL,
    IDEIA_ID_ORIGINAL INT NULL,
    TITULO_IDEIA VARCHAR(255) NOT NULL,
    DESCRICAO_IDEIA TEXT NULL,
    CATEGORIA_IDEIA VARCHAR(50) NULL,
    AUTOR_IDEIA_ID INT NULL,
    AUTOR_IDEIA_NOME VARCHAR(100) NULL,
    USUARIOS_ID INT NOT NULL,

    MOTIVO VARCHAR(100) NOT NULL,
    DESCRICAO TEXT,

    STATUS VARCHAR(30) NOT NULL DEFAULT 'Pendente',
    RESULTADO VARCHAR(30) NULL,
    MEDIDA_APLICADA VARCHAR(50) NULL,
    JUSTIFICATIVA TEXT NULL,
    ADMIN_ID INT NULL,

    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    RESOLVIDA_AT TIMESTAMP NULL,

    CONSTRAINT fk_denuncias_ideia
        FOREIGN KEY (IDEIAS_ID)
        REFERENCES IDEIAS(ID)
        ON DELETE SET NULL,

    CONSTRAINT fk_denuncias_usuario
        FOREIGN KEY (USUARIOS_ID)
        REFERENCES USUARIOS(ID)
        ON DELETE CASCADE,

    CONSTRAINT fk_denuncias_admin
        FOREIGN KEY (ADMIN_ID)
        REFERENCES USUARIOS(ID)
        ON DELETE SET NULL
);

-- ============================================================
-- RASCUNHOS DAS DENUNCIAS
-- ============================================================

CREATE TABLE IF NOT EXISTS RASCUNHOS_DENUNCIAS (
    ID INT AUTO_INCREMENT PRIMARY KEY,

    DENUNCIA_ID INT NOT NULL,
    ADMIN_ID INT NOT NULL,

    RESULTADO VARCHAR(30) NULL,
    MEDIDA_APLICADA VARCHAR(50) NULL,
    JUSTIFICATIVA TEXT NULL,

    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT fk_rascunho_denuncia
        FOREIGN KEY (DENUNCIA_ID)
        REFERENCES DENUNCIAS(ID)
        ON DELETE CASCADE,

    CONSTRAINT fk_rascunho_admin
        FOREIGN KEY (ADMIN_ID)
        REFERENCES USUARIOS(ID)
        ON DELETE CASCADE,

    CONSTRAINT uk_rascunho_denuncia_admin
        UNIQUE (DENUNCIA_ID, ADMIN_ID)
);

-- ============================================================
-- TABELA: ADVERTENCIAS
