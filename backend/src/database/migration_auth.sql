-- ============================================================
-- TABELA: RECUPERAÇÃO DE SENHA
-- ============================================================

CREATE TABLE RECUPERACAO_SENHA (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    USUARIOS_ID INT NOT NULL,
    TOKEN_HASH VARCHAR(64) NOT NULL UNIQUE,
    EXPIRA_AT DATETIME NOT NULL,
